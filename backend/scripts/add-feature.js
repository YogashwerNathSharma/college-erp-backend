/**
 * add-feature.js — Self-Guiding ERP, Phase 3 (Scaffolder)
 * ─────────────────────────────────────────────────────────────
 * Interactively creates a NEW backend module in the repo's real
 * 3-file pattern: <name>.routes.ts + <name>.controller.ts + <name>.service.ts
 *
 * Why no Plop? Zero new dependencies. Pure Node. Matches YOUR
 * existing structure (routes/controller/service, Prisma via
 * ../../utils/prisma, tenant scoping from req.user).
 *
 * Run:  npm run add-feature
 *
 * It will:
 *   1. Ask: module name (e.g. "scholarship")
 *   2. Ask: does this model belong to a tenant? (adds tenantId scoping)
 *   3. Generate backend/src/modules/<name>/ with 3 files
 *   4. Print EXACT next steps: app.ts mount line + where to add logic
 *   5. Refuse to overwrite an existing module (safe)
 */

const fs = require("fs");
const path = require("path");
const readline = require("readline");

const MODULES_DIR = path.join(__dirname, "..", "src", "modules");

const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
const ask = (q) => new Promise((res) => rl.question(q, (a) => res(a.trim())));

// pascalCase + camelCase helpers
function toCamel(s) {
  return s.replace(/[-_\s]+(.)?/g, (_, c) => (c ? c.toUpperCase() : "")).replace(/^(.)/, (m) => m.toLowerCase());
}
function toPascal(s) {
  const c = toCamel(s);
  return c.charAt(0).toUpperCase() + c.slice(1);
}

function serviceTemplate(name, tenantScoped) {
  const Camel = toPascal(name);
  const camel = toCamel(name);
  const scope = tenantScoped
    ? `  // Tenant-safe: always scope by tenantId (never trust client tenantId).\n  return prisma.${camel}.findMany({ where: { tenantId } });`
    : `  return prisma.${camel}.findMany();`;
  const createScope = tenantScoped
    ? `  return prisma.${camel}.create({ data: { ...data, tenantId } });`
    : `  return prisma.${camel}.create({ data });`;
  return `import prisma from "../../utils/prisma";

// ============================================================
// ${Camel} Service — business logic + Prisma access
// Generated by scripts/add-feature.js. Fill in your real logic.
// ============================================================

export const getAll${Camel}Service = async (${tenantScoped ? "tenantId: string" : ""}) => {
${scope}
};

export const create${Camel}Service = async (${tenantScoped ? "tenantId: string, data: any" : "data: any"}) => {
  // TODO: validate input (zod) and enforce business rules here.
${createScope}
};
`;
}

function controllerTemplate(name, tenantScoped) {
  const Camel = toPascal(name);
  const tid = tenantScoped ? `    const tenantId = (req as any).user?.tenantId;\n    if (!tenantId) return res.status(401).json({ success: false, message: "Unauthorized" });\n` : "";
  const getCall = tenantScoped ? `getAll${Camel}Service(tenantId)` : `getAll${Camel}Service()`;
  const createCall = tenantScoped ? `create${Camel}Service(tenantId, req.body)` : `create${Camel}Service(req.body)`;
  return `import { Request, Response } from "express";
import { getAll${Camel}Service, create${Camel}Service } from "./${name}.service";

// ============================================================
// ${Camel} Controller — parse req, call service, send json
// Generated by scripts/add-feature.js.
// ============================================================

export const getAll${Camel} = async (req: Request, res: Response) => {
  try {
${tid}    const data = await ${getCall};
    res.json({ success: true, data });
  } catch (error: any) {
    res.status(500).json({ success: false, message: error.message });
  }
};

export const create${Camel} = async (req: Request, res: Response) => {
  try {
${tid}    const data = await ${createCall};
    res.status(201).json({ success: true, data });
  } catch (error: any) {
    res.status(400).json({ success: false, message: error.message });
  }
};
`;
}

function routesTemplate(name) {
  const Camel = toPascal(name);
  return `import { Router } from "express";
import { authMiddleware } from "../../middleware/auth.middleware";
import { getAll${Camel}, create${Camel} } from "./${name}.controller";

const router = Router();

// All routes require authentication (adjust as needed).
router.use(authMiddleware);

// Static routes BEFORE dynamic (/:id) — repo convention.
router.get("/", getAll${Camel});
router.post("/", create${Camel});

export default router;
`;
}

async function main() {
  console.log("\\n=== Add Feature (new module scaffolder) ===\\n");
  let name = await ask("Module name (e.g. scholarship, lab-exam): ");
  name = name.toLowerCase().replace(/[^a-z0-9-]/g, "-").replace(/-+/g, "-").replace(/^-|-$/g, "");
  if (!name) { console.log("❌ Invalid name."); rl.close(); return; }

  const modDir = path.join(MODULES_DIR, name);
  if (fs.existsSync(modDir)) {
    console.log(`❌ Module "${name}" already exists at ${modDir}. Aborting (no overwrite).`);
    rl.close();
    return;
  }

  const tAns = (await ask("Is this data tenant-owned? (adds tenantId scoping) [Y/n]: ")).toLowerCase();
  const tenantScoped = tAns !== "n" && tAns !== "no";

  fs.mkdirSync(modDir, { recursive: true });
  fs.writeFileSync(path.join(modDir, `${name}.service.ts`), serviceTemplate(name, tenantScoped), "utf-8");
  fs.writeFileSync(path.join(modDir, `${name}.controller.ts`), controllerTemplate(name, tenantScoped), "utf-8");
  fs.writeFileSync(path.join(modDir, `${name}.routes.ts`), routesTemplate(name), "utf-8");

  const Camel = toPascal(name);
  console.log(`\\n✅ Module created: backend/src/modules/${name}/`);
  console.log(`   - ${name}.routes.ts`);
  console.log(`   - ${name}.controller.ts`);
  console.log(`   - ${name}.service.ts  ${tenantScoped ? "(tenant-scoped)" : "(global)"}`);

  console.log("\\n────────── NEXT STEPS (do these manually) ──────────\\n");
  console.log("1. Register the route in backend/src/app.ts. Add near the other mounts:");
  console.log(`\\n     import ${toCamel(name)}Routes from "./modules/${name}/${name}.routes";`);
  console.log(`     app.use("/api/${name}", ${toCamel(name)}Routes);\\n`);
  console.log(`2. Add the Prisma model "${toCamel(name)}" to prisma/schema.prisma`);
  if (tenantScoped) console.log(`   (include a tenantId field + @@index([tenantId])).`);
  console.log(`   Then run: npx prisma generate`);
  console.log(`\\n3. Write your real business logic in:`);
  console.log(`     backend/src/modules/${name}/${name}.service.ts  (getAll${Camel}Service / create${Camel}Service)`);
  console.log(`\\n4. Refresh the map:  npm run map:update`);
  console.log(`\\n5. Type-check:       npx tsc --noEmit\\n`);

  rl.close();
}

main();
