/**
 * generate-project-map.js
 * ─────────────────────────────────────────────────────────────
 * Self-Guiding ERP — Phase 2
 * Scans the backend and produces PROJECT_MAP.md at the repo root.
 *
 * What it maps (from YOUR actual code patterns):
 *   1. Route mounts in src/app.ts  (app.use("/api/...", ...))
 *   2. Every *.routes.ts file -> each router.METHOD("/path", handlers)
 *   3. The module each route belongs to + its controller/service files
 *
 * No new dependencies. Pure Node + regex. Run with:
 *   node scripts/generate-project-map.js
 *   (or:  npm run map:update)
 *
 * NOTE: This is a static scanner, not a type-aware parser. It reads
 * the literal route strings. If a route is built dynamically it may
 * be missed — treat the map as a strong guide, not a 100% guarantee.
 */

const fs = require("fs");
const path = require("path");

const BACKEND_SRC = path.join(__dirname, "..", "src");
const APP_FILE = path.join(BACKEND_SRC, "app.ts");
const MODULES_DIR = path.join(BACKEND_SRC, "modules");
const OUT_FILE = path.join(__dirname, "..", "..", "PROJECT_MAP.md");

// ── helpers ──────────────────────────────────────────────────
function walk(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, acc);
    else acc.push(full);
  }
  return acc;
}

function rel(p) {
  return path.relative(path.join(__dirname, "..", ".."), p).replace(/\\/g, "/");
}

// ── 1. Parse app.ts mounts ───────────────────────────────────
// Matches: app.use("/api/fees", moduleGate("fees"), feesRoutes);
function parseMounts() {
  const src = fs.readFileSync(APP_FILE, "utf-8");
  const mounts = [];
  const re = /app\.use\(\s*["'`]([^"'`]+)["'`]\s*,([^)]*)\)/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    const base = m[1];
    const rest = m[2];
    if (!base.startsWith("/api")) continue;
    // last identifier in the args = the Router variable
    const ids = rest.match(/[A-Za-z0-9_]+/g) || [];
    const routerVar = ids[ids.length - 1];
    const guards = [];
    if (/authMiddleware/.test(rest)) guards.push("auth");
    const rolesM = rest.match(/allowRoles\(([^)]*)\)/);
    if (rolesM) guards.push("roles(" + rolesM[1].replace(/["'`\s]/g, "") + ")");
    const gateM = rest.match(/moduleGate\(\s*["'`]([^"'`]+)["'`]\s*\)/);
    if (gateM) guards.push("module:" + gateM[1]);
    mounts.push({ base, routerVar, guards });
  }
  return mounts;
}

// ── 2. Parse each *.routes.ts file ───────────────────────────
// Matches: router.get("/search", authMiddleware, searchController)
function parseRouteFile(file) {
  const src = fs.readFileSync(file, "utf-8");
  const routes = [];
  const re = /router\.(get|post|put|patch|delete)\(\s*["'`]([^"'`]*)["'`]\s*,?([^)]*)\)/gi;
  let m;
  const lines = src.split(/\r?\n/);
  while ((m = re.exec(src)) !== null) {
    const method = m[1].toUpperCase();
    const subPath = m[2];
    const rest = m[3] || "";
    const handlers = (rest.match(/[A-Za-z0-9_]+/g) || []);
    const handler = handlers.length ? handlers[handlers.length - 1] : "(inline)";
    // line number
    const upto = src.slice(0, m.index);
    const line = upto.split(/\r?\n/).length;
    routes.push({ method, subPath, handler, line });
  }
  // router-level guards (router.use(...))
  const guards = [];
  if (/router\.use\([^)]*authMiddleware/.test(src)) guards.push("auth");
  const r = src.match(/router\.use\([^)]*allowRoles\(([^)]*)\)/);
  if (r) guards.push("roles(" + r[1].replace(/["'`\s]/g, "") + ")");
  return { routes, guards };
}

// ── 3. Build module index ────────────────────────────────────
function buildModuleIndex() {
  const files = walk(MODULES_DIR);
  const byModule = {};
  for (const f of files) {
    const r = rel(f);
    // backend/src/modules/<module>/<file>
    const parts = r.split("/");
    const mi = parts.indexOf("modules");
    if (mi === -1 || !parts[mi + 1]) continue;
    const mod = parts[mi + 1];
    byModule[mod] = byModule[mod] || { routes: [], controllers: [], services: [], others: [] };
    if (/\.routes\.ts$/.test(f)) byModule[mod].routes.push(f);
    else if (/\.controller\.ts$/.test(f)) byModule[mod].controllers.push(f);
    else if (/\.service\.ts$/.test(f)) byModule[mod].services.push(f);
    else if (/\.ts$/.test(f)) byModule[mod].others.push(f);
  }
  return byModule;
}

// ── main ─────────────────────────────────────────────────────
function main() {
  const mounts = parseMounts();
  const byModule = buildModuleIndex();

  let out = "";
  out += "# PROJECT_MAP.md\n\n";
  out += "> Auto-generated by `scripts/generate-project-map.js`. Do NOT edit by hand.\n";
  out += "> Run `npm run map:update` after changing routes/modules.\n";
  out += "> Generated: " + new Date().toISOString() + "\n\n";

  // Summary
  const totalModules = Object.keys(byModule).length;
  out += "## Summary\n\n";
  out += "- Modules: **" + totalModules + "**\n";
  out += "- API mounts in app.ts: **" + mounts.length + "**\n\n";

  // Route mounts table
  out += "## 1. API Mounts (from `backend/src/app.ts`)\n\n";
  out += "| Base path | Router | Guards |\n|---|---|---|\n";
  for (const mt of mounts) {
    out += `| \`${mt.base}\` | ${mt.routerVar} | ${mt.guards.join(", ") || "-"} |\n`;
  }
  out += "\n";

  // Per-module detail
  out += "## 2. Modules & Endpoints\n\n";
  for (const mod of Object.keys(byModule).sort()) {
    const info = byModule[mod];
    out += `### \`${mod}\`\n\n`;
    if (info.routes.length) {
      for (const rf of info.routes) {
        const parsed = parseRouteFile(rf);
        out += `**Routes file:** \`${rel(rf)}\``;
        if (parsed.guards.length) out += ` _(router guards: ${parsed.guards.join(", ")})_`;
        out += "\n\n";
        if (parsed.routes.length) {
          out += "| Method | Sub-path | Handler | Line |\n|---|---|---|---|\n";
          for (const rt of parsed.routes) {
            out += `| ${rt.method} | \`${rt.subPath || "/"}\` | ${rt.handler} | ${rt.line} |\n`;
          }
          out += "\n";
        }
      }
    }
    const fileList = (arr, label) =>
      arr.length ? `- ${label}: ${arr.map((f) => "`" + rel(f).split("/").pop() + "`").join(", ")}\n` : "";
    out += fileList(info.controllers, "Controllers");
    out += fileList(info.services, "Services");
    out += "\n";
  }

  // Dependency hint
  out += "## 3. Change-impact hint\n\n";
  out += "- Editing a `*.service.ts` → check its `*.controller.ts` and `*.routes.ts` in the same module.\n";
  out += "- Editing `app.ts` mounts → affects ALL routes under that base path.\n";
  out += "- Editing shared middleware (`src/middleware/*`) → affects every route that uses it.\n";

  fs.writeFileSync(OUT_FILE, out, "utf-8");
  console.log("✅ PROJECT_MAP.md generated at repo root.");
  console.log("   Modules:", totalModules, "| API mounts:", mounts.length);
}

main();
